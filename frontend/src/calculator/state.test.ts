import { describe, expect, it } from 'vitest'
import { expressionTokens, initialState, reducer, serializeTokens } from './state'

const press = (keys: string[]) => keys.reduce((state, key) => {
  if (key === '.') return reducer(state, { type: 'decimal' })
  if (/^\d$/.test(key)) return reducer(state, { type: 'digit', value: key })
  if (key === '±') return reducer(state, { type: 'sign' })
  if (key === '⌫') return reducer(state, { type: 'backspace' })
  if (key === '(') return reducer(state, { type: 'openParen' })
  if (key === ')') return reducer(state, { type: 'closeParen' })
  const operators = { '+': '+', '-': '-', '*': '*', '/': '/', '^': '^' } as const
  return reducer(state, { type: 'operator', value: operators[key as keyof typeof operators] })
}, initialState)

describe('calculator reducer', () => {
  it('builds expressions and serializes negative numbers safely', () => {
    const state = press(['2', '^', '±', '1'])
    expect(serializeTokens(expressionTokens(state), 'api')).toBe('2 ^ (-1)')
  })
  it('replaces an operator and limits operands', () => {
    const state = press(['2', '+', '*'])
    expect(serializeTokens(state.tokens, 'api')).toBe('2 *')
    const long = press(Array.from({ length: 20 }, () => '1'))
    expect(long.current.length).toBe(15)
  })
  it('provides a completion hint and preserves history on clear', () => {
    const state = reducer(press(['2', '+']), { type: 'hint', value: 'Complete the expression first.' })
    const withHistory = reducer(state, { type: 'result', expression: '2', value: 2 })
    expect(withHistory.history).toHaveLength(1)
    expect(reducer(withHistory, { type: 'clear' }).history).toHaveLength(1)
  })
  it('handles decimals, signs, parentheses and deletion', () => {
    let state = press(['0', '5'])
    expect(state.current).toBe('5')
    state = reducer(state, { type: 'decimal' })
    expect(state.current).toBe('5.')
    state = reducer(state, { type: 'decimal' })
    expect(state.current).toBe('5.')
    state = reducer(state, { type: 'sign' })
    expect(state.current).toBe('-5.')
    state = reducer(state, { type: 'backspace' })
    expect(state.current).toBe('-5')
    state = reducer(state, { type: 'openParen' })
    expect(state.tokens).toHaveLength(0)
    state = reducer(initialState, { type: 'openParen' })
    state = reducer(state, { type: 'digit', value: '2' })
    state = reducer(state, { type: 'operator', value: '+' })
    state = reducer(state, { type: 'digit', value: '3' })
    state = reducer(state, { type: 'closeParen' })
    expect(state.tokens.at(-1)?.value).toBe(')')
  })
  it('ignores invalid placements and respects pending/error behavior', () => {
    expect(reducer(initialState, { type: 'closeParen' })).toEqual(initialState)
    const pending = reducer(initialState, { type: 'pending', value: true })
    expect(reducer(pending, { type: 'digit', value: '1' })).toBe(pending)
    const failed = reducer(reducer(pending, { type: 'error', value: 'bad' }), { type: 'pending', value: false })
    expect(reducer(failed, { type: 'operator', value: '+' })).toBe(failed)
    expect(reducer(failed, { type: 'digit', value: '2' }).current).toBe('2')
  })
  it('supports result chaining and history limits', () => {
    let state = reducer(initialState, { type: 'result', expression: '8', value: 8 })
    state = reducer(state, { type: 'operator', value: '+' })
    expect(serializeTokens(expressionTokens(state), 'api')).toBe('8 +')
    for (let index = 0; index < 25; index++) state = reducer(state, { type: 'result', expression: String(index), value: index })
    expect(state.history).toHaveLength(20)
    expect(reducer(state, { type: 'clearHistory' }).history).toHaveLength(0)
  })
  it('covers parenthesis and backspace transitions', () => {
    let state = reducer(initialState, { type: 'openParen' })
    state = reducer(state, { type: 'digit', value: '2' })
    state = reducer(state, { type: 'operator', value: '+' })
    state = reducer(state, { type: 'digit', value: '3' })
    state = reducer(state, { type: 'closeParen' })
    state = reducer(state, { type: 'backspace' })
    expect(state.current).toBe('3')
    state = reducer(state, { type: 'backspace' })
    expect(state.current).toBe('')
    expect(reducer({ ...initialState, current: '5', currentIsResult: true }, { type: 'backspace' }).current).toBe('5')
    expect(reducer({ ...initialState, error: 'bad' }, { type: 'backspace' }).error).toBeNull()
    expect(reducer({ ...initialState, tokens: [{ kind: 'paren', value: ')' }] }, { type: 'openParen' }).tokens).toHaveLength(1)
    expect(reducer(initialState, { type: 'unaryResult', expression: '√(9)', value: 3 }).history).toHaveLength(1)
  })
})
